package io.helidon.build.maven.services;

import java.io.IOException;
import java.io.InputStream;
import java.io.PrintWriter;
import java.io.StringWriter;
import java.net.URL;
import java.net.URLClassLoader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.ServiceLoader;
import java.util.Set;
import java.util.spi.ToolProvider;
import java.util.stream.Collectors;
import java.util.stream.Stream;
import java.util.zip.ZipFile;

import io.helidon.build.common.test.utils.ConfigurationParameterSource;
import io.helidon.build.common.test.utils.JUnitLauncher;

import org.junit.jupiter.api.condition.EnabledIfSystemProperty;
import org.junit.jupiter.params.ParameterizedTest;

import static io.helidon.build.common.Strings.normalizeNewLines;
import static org.hamcrest.MatcherAssert.assertThat;
import static org.hamcrest.Matchers.containsString;
import static org.hamcrest.Matchers.is;

/**
 * Integration test that verifies the projects under {@code src/it/projects}.
 */
@EnabledIfSystemProperty(named = JUnitLauncher.IDENTITY_PROP, matches = "true")
class ProjectsTestIT {

    private static final String RUNNABLE = "java.lang.Runnable";
    private static final String TOOL = "java.util.spi.ToolProvider";
    private static final String FIRST = "it.Services$First";
    private static final String SECOND = "it.Services$Second";
    private static final String TOOL_PROVIDER = "it.Services$Tool";
    private static final String DEFAULT_COMMENT = "# This file was generated by Helidon services Maven plugin.\n";

    @ParameterizedTest
    @ConfigurationParameterSource("basedir")
    void testGenerate(String basedir) throws IOException {
        Map<String, String> expected = Map.of(
                RUNNABLE,
                DEFAULT_COMMENT
                        + FIRST + "\n"
                        + SECOND + "\n",
                TOOL,
                DEFAULT_COMMENT
                        + TOOL_PROVIDER + "\n");
        Path jar = verifySuccess(basedir, expected, true);

        // on the class path, discovery depends on the packaged META-INF/services records
        try (URLClassLoader loader = new URLClassLoader(new URL[]{jar.toUri().toURL()},
                                                       ClassLoader.getPlatformClassLoader())) {
            Set<String> providers = new HashSet<>();
            ServiceLoader.load(Runnable.class, loader).forEach(provider -> providers.add(provider.getClass().getName()));
            assertThat("Class-path Runnable providers", providers, is(Set.of(FIRST, SECOND)));

            List<ToolProvider> tools = new ArrayList<>();
            ServiceLoader.load(ToolProvider.class, loader).forEach(tools::add);
            assertThat("Class-path ToolProvider count", tools.size(), is(1));
            ToolProvider tool = tools.get(0);
            assertThat("Class-path ToolProvider implementation", tool.getClass().getName(), is(TOOL_PROVIDER));
            assertThat("Packaged ToolProvider name", tool.name(), is("services-test"));
            assertThat("Packaged ToolProvider execution result",
                    tool.run(new PrintWriter(new StringWriter()), new PrintWriter(new StringWriter())), is(17));
        }
    }

    @ParameterizedTest
    @ConfigurationParameterSource("basedir")
    void testGenerateNoComment(String basedir) throws IOException {
        Map<String, String> expected = Map.of(
                RUNNABLE,
                FIRST + "\n"
                        + SECOND + "\n",
                TOOL,
                TOOL_PROVIDER + "\n");
        verifySuccess(basedir, expected, true);
    }

    @ParameterizedTest
    @ConfigurationParameterSource("basedir")
    void testOverwrite(String basedir) throws IOException {
        Map<String, String> expected = Map.of(
                RUNNABLE,
                DEFAULT_COMMENT
                        + FIRST + "\n"
                        + SECOND + "\n",
                TOOL,
                DEFAULT_COMMENT
                        + TOOL_PROVIDER + "\n");
        verifySuccess(basedir, expected, true);
        verifyRecords(Path.of(basedir).resolve("src/main/resources/META-INF/services"),
                Map.of(
                        RUNNABLE,
                        "stale.Provider\n",
                        "obsolete.Service",
                        "obsolete.Provider\n"));
    }

    @ParameterizedTest
    @ConfigurationParameterSource("basedir")
    void testIgnoreExisting(String basedir) throws IOException {
        Map<String, String> expected = Map.of(
                RUNNABLE,
                SECOND + "\n");
        verifySuccess(basedir, expected, true);
        verifyDiagnostic(basedir, "Ignoring module-info.java");
        verifyRecords(Path.of(basedir).resolve("src/main/resources/META-INF/services"), expected);
    }

    @ParameterizedTest
    @ConfigurationParameterSource("basedir")
    void testSkip(String basedir) throws IOException {
        Map<String, String> expected = Map.of(
                "kept.Service",
                "kept.Provider\n");
        verifySuccess(basedir, expected, true);
        verifyDiagnostic(basedir, "Skipping execution.");
        verifyRecords(Path.of(basedir).resolve("src/main/resources/META-INF/services"), expected);
    }

    @ParameterizedTest
    @ConfigurationParameterSource("basedir")
    void testMissingModuleSkip(String basedir) throws IOException {
        Map<String, String> expected = Map.of();
        verifySuccess(basedir, expected, false);
        verifyDiagnostic(basedir, "Skipping project with no module-info.");
    }

    @ParameterizedTest
    @ConfigurationParameterSource("basedir")
    void testFailExisting(String basedir) throws IOException {
        Map<String, String> expected = Map.of(
                RUNNABLE,
                FIRST + "\n");
        verifyFailure(basedir, expected, true);
        verifyDiagnostic(basedir, "Project must not contain META-INF/services in source folder");
        verifyRecords(Path.of(basedir).resolve("src/main/resources/META-INF/services"), expected);
    }

    @ParameterizedTest
    @ConfigurationParameterSource("basedir")
    void testValidateMatch(String basedir) throws IOException {
        Map<String, String> expected = Map.of(
                RUNNABLE,
                "# Providers are a set; order and duplicates do not matter.\n"
                        + SECOND + "\n"
                        + "\n"
                        + FIRST + "\n"
                        + SECOND + "\n",
                TOOL,
                "# Tool provider\n"
                        + "\n"
                        + TOOL_PROVIDER + "\n");
        verifySuccess(basedir, expected, true);
        verifyDiagnostic(basedir, "Services are valid.");
        verifyRecords(Path.of(basedir).resolve("src/main/resources/META-INF/services"), expected);
    }

    @ParameterizedTest
    @ConfigurationParameterSource("basedir")
    void testCleanSubset(String basedir) throws IOException {
        Map<String, String> expected = Map.of(
                RUNNABLE,
                "# A subset can safely be deleted.\n"
                        + FIRST + "\n");
        verifySuccess(basedir, expected, true);
        assertThat("Clean must remove source service directory",
                Files.exists(Path.of(basedir).resolve("src/main/resources/META-INF/services")), is(false));
    }

    private static Path verifySuccess(String basedir, Map<String, String> expected, boolean moduleInfo) throws IOException {
        Path project = Path.of(basedir);
        verifyRecords(project.resolve("target/classes/META-INF/services"), expected);
        assertThat("Compiled module descriptor existence",
                Files.exists(project.resolve("target/classes/module-info.class")), is(moduleInfo));

        List<Path> jars = jarFiles(project);
        assertThat("Packaged artifact count", jars.size(), is(1));
        Path jar = jars.get(0);
        try (ZipFile zip = new ZipFile(jar.toFile())) {
            Set<String> entries = zip.stream()
                    .filter(entry -> !entry.isDirectory() && entry.getName().startsWith("META-INF/services/"))
                    .map(entry -> entry.getName().substring("META-INF/services/".length()))
                    .collect(Collectors.toSet());
            assertThat("Packaged service entries in " + jar, entries, is(expected.keySet()));
            for (Map.Entry<String, String> record : expected.entrySet()) {
                try (InputStream input = zip.getInputStream(zip.getEntry("META-INF/services/" + record.getKey()))) {
                    String content = new String(input.readAllBytes(), StandardCharsets.UTF_8);
                    assertThat("Packaged service record " + record.getKey(),
                            normalizeNewLines(content), is(record.getValue()));
                }
            }
        }
        return jar;
    }

    private static void verifyFailure(String basedir, Map<String, String> expected, boolean moduleInfo) throws IOException {
        Path project = Path.of(basedir);
        verifyRecords(project.resolve("target/classes/META-INF/services"), expected);
        assertThat("Compiled module descriptor existence",
                Files.exists(project.resolve("target/classes/module-info.class")), is(moduleInfo));
        assertThat("A failed services execution must prevent packaging", jarFiles(project), is(List.of()));
    }

    private static List<Path> jarFiles(Path project) throws IOException {
        try (Stream<Path> files = Files.list(project.resolve("target"))) {
            return files.filter(Files::isRegularFile)
                    .filter(path -> path.getFileName().toString().endsWith(".jar"))
                    .collect(Collectors.toList());
        }
    }

    private static void verifyRecords(Path directory, Map<String, String> expected) throws IOException {
        Set<String> names = new HashSet<>();
        if (Files.isDirectory(directory)) {
            try (Stream<Path> files = Files.list(directory)) {
                files.forEach(path -> names.add(path.getFileName().toString()));
            }
        }
        assertThat("Service file names in " + directory, names, is(expected.keySet()));
        for (Map.Entry<String, String> record : expected.entrySet()) {
            Path descriptor = directory.resolve(record.getKey());
            assertThat("Service descriptor must be a file: " + descriptor, Files.isRegularFile(descriptor), is(true));
            assertThat("Service descriptor contents: " + descriptor,
                    normalizeNewLines(Files.readString(descriptor)), is(record.getValue()));
        }
    }

    private static void verifyDiagnostic(String basedir, String diagnostic) throws IOException {
        String log = Files.readString(Path.of(basedir).resolve("build.log"));
        assertThat("Services diagnostic in build.log", log, containsString(diagnostic));
    }
}
