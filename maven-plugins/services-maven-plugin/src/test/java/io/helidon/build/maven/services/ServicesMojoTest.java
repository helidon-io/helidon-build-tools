import static io.helidon.build.common.Strings.normalizeNewLines;
import static org.hamcrest.CoreMatchers.containsString;
import static org.hamcrest.CoreMatchers.is;
import static org.hamcrest.CoreMatchers.notNullValue;
import static org.hamcrest.MatcherAssert.assertThat;
import static org.junit.jupiter.api.Assertions.assertThrows;

class ServicesMojoTest {
    private static final String RUNNABLE = "java.lang.Runnable";
    private static final String TOOL = "java.util.spi.ToolProvider";
    private static final String FIRST = "it.Services$First";
    private static final String SECOND = "it.Services$Second";
    private static final String TOOL_PROVIDER = "it.Services$Tool";
    private static final String COMMENT = "# This file was generated by Helidon services Maven plugin.\n";

    @TempDir
    private static Path compiled;

    @TempDir
    private Path directory;

    private MojoConfiguration configuration;
    private Path sourceServices;
    private Path targetServices;

    @BeforeAll
    static void compileModules() throws IOException {
        JavaCompiler compiler = ToolProvider.getSystemJavaCompiler();
        assertThat("Tests require a JDK compiler", compiler, notNullValue());
        for (String module : List.of("providers", "empty")) {
            Path source = Path.of("src/test/resources/modules", module);
            Path output = Files.createDirectories(compiled.resolve(module));
            DiagnosticCollector<JavaFileObject> diagnostics = new DiagnosticCollector<>();
            try (Stream<Path> paths = Files.walk(source);
                 StandardJavaFileManager manager = compiler.getStandardFileManager(diagnostics, null, null)) {
                List<Path> sources = paths.filter(path -> path.toString().endsWith(".java"))
                        .collect(Collectors.toList());
                boolean success = compiler.getTask(null,
                                                   manager,
                                                   diagnostics,
                                                   List.of("--release", "11", "-d", output.toString()),
                                                   null,
                                                   manager.getJavaFileObjectsFromPaths(sources))
                        .call();
                assertThat("Compilation of " + module + ": " + diagnostics.getDiagnostics(), success, is(true));
            }
        }
    }

    @BeforeEach
    void setUp() throws Exception {
        configuration = new MojoConfiguration();
        configuration.initialize();
        sourceServices = directory.resolve("src/main/resources/META-INF/services");
        targetServices = directory.resolve("target/classes/META-INF/services");
    }

    @AfterEach
    void tearDown() throws Exception {
        if (configuration != null) {
            configuration.close();
        }
    }

    @Test
    void testIgnoreGenerate() throws Exception {
        module("providers");
        execute("ignore", "jar", "Created");
        verifyRecords(targetServices, Map.of(RUNNABLE, COMMENT + FIRST + "\n" + SECOND + "\n",
                                            TOOL, COMMENT + TOOL_PROVIDER + "\n"));
        verifyRecords(sourceServices, Map.of());
    }

    @Test
    void testNoSources() throws Exception {
        execute("fail", "jar", "Skipping project with no sources");
        verifyRecords(sourceServices, Map.of());
        verifyRecords(targetServices, Map.of());
    }

    @Test
    void testPomPackaging() throws Exception {
        Files.createDirectories(directory.resolve("src/main/java"));
        execute("fail", "pom", "Skipping POM packaging project");
        verifyRecords(sourceServices, Map.of());
        verifyRecords(targetServices, Map.of());
    }

    @Test
    void testMissingModuleFail() throws Exception {
        Files.createDirectories(directory.resolve("src/main/java"));
        verifyFailure("fail", "Project does not contain module-info.class");
        verifyRecords(sourceServices, Map.of());
        verifyRecords(targetServices, Map.of());
    }

    @Test
    void testValidateMissingService() throws Exception {
        verifyValidateFailure(Map.of(RUNNABLE, FIRST + "\n" + SECOND + "\n"),
                              "Service java.util.spi.ToolProvider missing from META-INF/services");
    }

    @Test
    void testValidateExtraService() throws Exception {
        verifyValidateFailure(Map.of(RUNNABLE, FIRST + "\n" + SECOND + "\n",
                                     TOOL, TOOL_PROVIDER + "\n", "extra.Service", "extra.Provider\n"),
                              "Service extra.Service missing from module-info.java");
    }

    @Test
    void testValidateMissingProvider() throws Exception {
        verifyValidateFailure(Map.of(RUNNABLE, FIRST + "\n", TOOL, TOOL_PROVIDER + "\n"),
                              "Service java.lang.Runnable is missing the following providers in META-INF/services:"
                                      + " [it.Services$Second]");
    }

    @Test
    void testValidateExtraProvider() throws Exception {
        verifyValidateFailure(Map.of(RUNNABLE, FIRST + "\n" + SECOND + "\nextra.Provider\n",
                                     TOOL, TOOL_PROVIDER + "\n"),
                              "Service java.lang.Runnable is missing the following providers in module-info.java:"
                                      + " [extra.Provider]");
    }

    @Test
    void testCleanNoSource() throws Exception {
        module("providers");
        Map<String, String> target = Map.of("target.Service", "target.Provider\n");
        writeRecords(targetServices, target);
        execute("clean", "jar", "Mode is");
        assertThat("Clean must not create source service directory", Files.exists(sourceServices), is(false));
        verifyRecords(targetServices, target);
    }

    @Test
    void testCleanExtraService() throws Exception {
        verifyCleanFailure("providers", Map.of(RUNNABLE, FIRST + "\n", "extra.Service", "extra.Provider\n"),
                           "Service extra.Service missing from module-info.java");
    }

    @Test
    void testCleanExtraProvider() throws Exception {
        verifyCleanFailure("providers", Map.of(RUNNABLE, FIRST + "\n" + SECOND + "\nextra.Provider\n",
                                               TOOL, TOOL_PROVIDER + "\n"),
                           "Service java.lang.Runnable is missing the following providers in module-info.java:"
                                   + " [extra.Provider]");
    }

    @Test
    void testCleanNoProvides() throws Exception {
        verifyCleanFailure("empty", Map.of(RUNNABLE, FIRST + "\n"),
                           "module-info.java does not define any service providers");
    }

    @Test
    void testEmptyModule() throws Exception {
        module("empty");
        execute("fail", "jar", "There are no services provided by this module.");
        verifyRecords(sourceServices, Map.of());
        verifyRecords(targetServices, Map.of());
    }

    @Test
    void testInvalidMode() throws Exception {
        module("providers");
        verifyFailure("unknown", "Invalid plugin mode 'unknown'");
        verifyRecords(sourceServices, Map.of());
        verifyRecords(targetServices, Map.of());
    }

    private static void writeRecords(Path path, Map<String, String> records) throws IOException {
        Files.createDirectories(path);
        for (Map.Entry<String, String> record : records.entrySet()) {
            Files.writeString(path.resolve(record.getKey()), record.getValue());
        }
    }

    private static void verifyRecords(Path path, Map<String, String> expected) throws IOException {
        Set<String> names = Set.of();
        if (Files.isDirectory(path)) {
            try (Stream<Path> files = Files.list(path)) {
                names = files.map(file -> file.getFileName().toString()).collect(Collectors.toSet());
            }
        }
        assertThat("Service file names in " + path, names, is(expected.keySet()));
        for (Map.Entry<String, String> record : expected.entrySet()) {
            Path file = path.resolve(record.getKey());
            assertThat("Service descriptor must be a file: " + file, Files.isRegularFile(file), is(true));
            assertThat("Service descriptor contents: " + file,
                       normalizeNewLines(Files.readString(file)), is(record.getValue()));
        }
    }

    private void module(String name) throws IOException {
        Files.createDirectories(directory.resolve("src/main/java"));
        Path output = Files.createDirectories(directory.resolve("target/classes"));
        Files.copy(compiled.resolve(name).resolve("module-info.class"), output.resolve("module-info.class"));
    }

    private void execute(String mode, String packaging, String diagnostic) throws Exception {
        ServicesMojo mojo = configuration.mojo(directory, mode, packaging);
        try (LogRecorder recorder = new LogRecorder(LogLevel.DEBUG).start()) {
            mojo.execute();
            assertThat("Services diagnostic", recorder.output(), containsString(diagnostic));
        }
    }

    private void verifyFailure(String mode, String diagnostic) throws Exception {
        ServicesMojo mojo = configuration.mojo(directory, mode, "jar");
        MojoExecutionException error = assertThrows(MojoExecutionException.class, mojo::execute);
        assertThat("Services failure diagnostic", error.getMessage(), containsString(diagnostic));
    }

    private void verifyValidateFailure(Map<String, String> target, String diagnostic) throws Exception {
        module("providers");
        Map<String, String> source = Map.of(RUNNABLE, FIRST + "\n" + SECOND + "\n", TOOL, TOOL_PROVIDER + "\n");
        writeRecords(sourceServices, source);
        writeRecords(targetServices, target);
        verifyFailure("validate", diagnostic);
        verifyRecords(sourceServices, source);
        verifyRecords(targetServices, target);
    }

    private void verifyCleanFailure(String module, Map<String, String> source, String diagnostic) throws Exception {
        module(module);
        Map<String, String> target = Map.of("target.Service", "target.Provider\n");
        writeRecords(sourceServices, source);
        writeRecords(targetServices, target);
        verifyFailure("clean", diagnostic);
        verifyRecords(sourceServices, source);
        verifyRecords(targetServices, target);
    }

    @SuppressWarnings("UnconstructableJUnitTestCase")
    private static final class MojoConfiguration extends AbstractMojoTestCase implements AutoCloseable {
        private final Logger previousLogger = PlexusLoggerHolder.REF.get();
        private final LogLevel previousLevel = LogLevel.get();

        void initialize() throws Exception {
            super.setUp();
            // maven normally initializes this component before executing plugin goals
            getContainer().lookup(PlexusLoggerHolder.class);
        }

        ServicesMojo mojo(Path directory, String mode, String packaging) throws Exception {
            Model model = new Model();
            model.setModelVersion("4.0.0");
            model.setGroupId("it");
            model.setArtifactId("services-test");
            model.setVersion("1");
            model.setPackaging(packaging);
            Build build = new Build();
            build.setDirectory(directory.resolve("target").toString());
            build.setSourceDirectory(directory.resolve("src/main/java").toString());
            build.setOutputDirectory(directory.resolve("target/classes").toString());
            model.setBuild(build);
            Plugin plugin = new Plugin();
            plugin.setGroupId("io.helidon.build-tools");
            plugin.setArtifactId("helidon-services-plugin");
            Xpp3Dom configuration = new Xpp3Dom("configuration");
            Map<String, String> parameters = Map.of("mode", mode,
                                                   "javaDirectory", build.getSourceDirectory(),
                                                   "targetDirectory", build.getOutputDirectory(),
                                                   "baseDir", directory.toString(),
                                                   "resourceDirectory", directory.resolve("src/main/resources").toString());
            parameters.forEach((name, value) -> {
                Xpp3Dom parameter = new Xpp3Dom(name);
                parameter.setValue(value);
                configuration.addChild(parameter);
            });
            plugin.setConfiguration(configuration);
            build.addPlugin(plugin);
            MavenProject project = new MavenProject(model);
            project.setFile(directory.resolve("pom.xml").toFile());
            ServicesMojo mojo = (ServicesMojo) lookupConfiguredMojo(newMavenSession(project), newMojoExecution("services"));
            assertThat("Configured services Mojo", mojo, notNullValue());
            return mojo;
        }

        @Override
        public void close() throws Exception {
            try {
                super.tearDown();
            } finally {
                PlexusLoggerHolder.REF.set(previousLogger);
                LogLevel.set(previousLevel);
            }
        }
    }
}
